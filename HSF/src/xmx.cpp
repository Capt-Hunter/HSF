LogFunction g_log = nullptr;
std::atomic<uint32_t> g_lines{0};
// At most 64 lines a process from XeMFG, as theirs keeps to 48: a fault that repeats every frame must not fill HSF.log.
void Line(const char* format, ...) {
  if (g_log == nullptr || g_lines.fetch_add(1, std::memory_order_relaxed) >= 64) return;
  char text[512] = "XeMFG: ";
  va_list args;
  va_start(args, format);
  vsnprintf(text + 7, sizeof(text) - 7, format, args);
  va_end(args);
  g_log(text);
}

// What happened to the generated frames DLSS-G asked for: made by XeFG, the real frame shown again (no pair, a reset, past the model's
// limit, a failure), or XeFG's Execute refused. One line every 5 s while frames come, outside the 64-line limit: it is the one proof that XeFG
// makes the frames, since a repeated frame looks the same to an fps counter.
std::atomic<uint64_t> g_made{0}, g_repeated{0}, g_refused{0};
uint64_t g_stats_tick = 0;
uint64_t g_stats_made = 0, g_stats_repeated = 0, g_stats_refused = 0;
void Stats() {
  // NGX may evaluate from more than one thread; whoever holds this writes the line.
  static std::mutex lock;
  std::unique_lock<std::mutex> guard(lock, std::try_to_lock);
  if (!guard.owns_lock()) return;
  const uint64_t now = GetTickCount64();
  if (g_stats_tick == 0) g_stats_tick = now;
  if (now - g_stats_tick < 5000 || g_log == nullptr) return;
  g_stats_tick = now;
  const uint64_t made = g_made.load(std::memory_order_relaxed), repeated = g_repeated.load(std::memory_order_relaxed),
                 refused = g_refused.load(std::memory_order_relaxed);
  char text[256];
  snprintf(text, sizeof(text), "XeMFG: last 5 s: %llu generated by XeFG, %llu real frames shown again, %llu refused by XeFG",
           static_cast<unsigned long long>(made - g_stats_made), static_cast<unsigned long long>(repeated - g_stats_repeated),
           static_cast<unsigned long long>(refused - g_stats_refused));
  g_stats_made = made;
  g_stats_repeated = repeated;
  g_stats_refused = refused;
  g_log(text);
}

